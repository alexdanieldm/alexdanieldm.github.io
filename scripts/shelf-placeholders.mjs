/**
 * Writes `src/content/shelf-placeholders.ts`: every poster on the shelf at
 * 12x18, as a WebP data URI. The page carries them inline, so each card shows
 * its own poster blurred from the first paint and sharpens when the real file
 * lands, instead of sitting empty while it loads.
 *
 * Run it after adding or replacing a poster: `npm run shelf:placeholders`. The
 * deploy runs it again before every build, so a poster added without it still
 * ships with its placeholder. It reads the 360 files, the smallest on disk;
 * anything larger is wasted at twelve pixels.
 *
 * sharp is not a dependency of this repo. It is already installed because Next
 * depends on it, and this runs as a step of its own, never inside `next build`.
 */

import { readdirSync, writeFileSync } from 'node:fs';

import sharp from 'sharp';

const DIR = 'public/shelf';
const OUT = 'src/content/shelf-placeholders.ts';
const SUFFIX = '-360.webp';

/* 12x18 at quality 50 averages 240 characters a poster, 8KB for the shelf.
   8x12 saves 2KB and loses what makes one poster's blur differ from the next. */
const WIDTH = 12;
const HEIGHT = 18;
const QUALITY = 50;

const slugs = readdirSync(DIR)
  .filter((file) => file.endsWith(SUFFIX))
  .map((file) => file.slice(0, -SUFFIX.length))
  .sort();

const entries = [];
for (const slug of slugs) {
  const tiny = await sharp(`${DIR}/${slug}${SUFFIX}`)
    .resize(WIDTH, HEIGHT)
    .webp({ quality: QUALITY })
    .toBuffer();
  /* Laid out the way Prettier lays it out, so the file passes the format check
     as written: a key quoted only when the slug needs it, and the value on its
     own line, since no data URI fits beside its key in 100 columns. */
  const key = /^[a-z_$][\w$]*$/i.test(slug) ? slug : `'${slug}'`;
  entries.push(`  ${key}:\n    'data:image/webp;base64,${tiny.toString('base64')}',`);
}

writeFileSync(
  OUT,
  `/**
 * @fileoverview Each poster at ${WIDTH}x${HEIGHT}, inlined. Generated by
 * \`npm run shelf:placeholders\` from the files in \`public/shelf/\`; run that
 * again rather than editing this by hand.
 */

export const POSTER_PLACEHOLDERS: Record<string, string> = {
${entries.join('\n')}
};
`,
);

console.log(`${slugs.length} placeholders written to ${OUT}`);
